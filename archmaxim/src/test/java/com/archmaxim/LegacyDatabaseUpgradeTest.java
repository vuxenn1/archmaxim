/**
 * Starts the app on a database in the state the previous version left it in:
 * tables generated by Hibernate, the embedding column added at startup, nullable
 * counters and duplicate aliases. Flyway has to adopt it without losing data.
 */
@SpringBootTest(properties = {
        "archmaxim.jwt.secret=" + TestProperties.SECRET,
        "archmaxim.search.max-distance=0.95"
})
@AutoConfigureMockMvc
@Testcontainers(disabledWithoutDocker = true)
class LegacyDatabaseUpgradeTest {

    private static final String LEGACY_ADMIN_PASSWORD = "admin123";

    @Container
    static PostgreSQLContainer postgres = new PostgreSQLContainer(
            DockerImageName.parse("pgvector/pgvector:pg17").asCompatibleSubstituteFor("postgres"));

    @DynamicPropertySource
    static void legacyDatabase(DynamicPropertyRegistry registry) throws Exception {
        createLegacySchema();
        Path storage = Files.createTempDirectory("archmaxim-legacy");
        Files.writeString(storage.resolve("legacy-uuid"), "old exam");

        registry.add("spring.datasource.url", postgres::getJdbcUrl);
        registry.add("spring.datasource.username", postgres::getUsername);
        registry.add("spring.datasource.password", postgres::getPassword);
        registry.add("archmaxim.storage.location", storage::toString);
    }

    @Autowired
    private MockMvc mvc;

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @MockitoBean
    private EmbeddingClient embeddingClient;

    @Test
    void adoptsTheOldSchemaAndKeepsItsData() throws Exception {
        when(embeddingClient.embed(anyString())).thenAnswer(call -> FakeEmbeddings.of(call.getArgument(0)));
        when(embeddingClient.embedAll(anyList())).thenAnswer(call -> {
            List<String> texts = call.getArgument(0);
            return texts.stream().map(FakeEmbeddings::of).toList();
        });

        assertThat(jdbcTemplate.queryForList("SELECT normalized_alias FROM course_alias ORDER BY id", String.class))
                .containsExactly("bp2", "bilprog2");
        assertThat(jdbcTemplate.queryForObject("SELECT download_count FROM file_record WHERE id = 1", Integer.class))
                .isZero();
        assertThat(jdbcTemplate.queryForObject("SELECT is_active FROM file_record WHERE id = 1", Boolean.class))
                .isTrue();

        String body = mvc.perform(post("/auth/login")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("{\"email\":\"admin@archmaxim.edu\",\"password\":\"" + LEGACY_ADMIN_PASSWORD + "\"}"))
                .andExpect(status().isOk())
                .andReturn().getResponse().getContentAsString(StandardCharsets.UTF_8);
        String admin = "Bearer " + JsonPath.read(body, "$.token");

        mvc.perform(post("/files/index").header(HttpHeaders.AUTHORIZATION, admin))
                .andExpect(status().isAccepted())
                .andExpect(jsonPath("$.started").value(true));
        waitForIndexing(admin);

        mvc.perform(get("/files/search").param("query", "bp2 vize").header(HttpHeaders.AUTHORIZATION, admin))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$[0].id").value(1))
                .andExpect(jsonPath("$[0].originalName").value("eski_vize.pdf"));

        mvc.perform(get("/files/1/download").header(HttpHeaders.AUTHORIZATION, admin))
                .andExpect(status().isOk());
    }

    private void waitForIndexing(String admin) throws Exception {
        Instant deadline = Instant.now().plus(Duration.ofSeconds(20));
        while (Instant.now().isBefore(deadline)) {
            String status = mvc.perform(get("/files/index/status").header(HttpHeaders.AUTHORIZATION, admin))
                    .andReturn().getResponse().getContentAsString();
            if (!(Boolean) JsonPath.read(status, "$.running") && JsonPath.read(status, "$.finishedAt") != null) {
                assertThat((Integer) JsonPath.read(status, "$.processed")).isEqualTo(1);
                return;
            }
            Thread.sleep(100);
        }
        throw new AssertionError("Indexing did not finish in time");
    }

    // Shaped like the DDL Hibernate's ddl-auto=update produced for the old entities.
    private static void createLegacySchema() throws Exception {
        String adminHash = new BCryptPasswordEncoder().encode(LEGACY_ADMIN_PASSWORD);
        try (Connection connection = DriverManager.getConnection(
                postgres.getJdbcUrl(), postgres.getUsername(), postgres.getPassword());
             Statement sql = connection.createStatement()) {
            sql.execute("""
                    create table admin (created_at timestamp(6), id bigint generated by default as identity,
                        email varchar(255) unique, first_name varchar(255), last_name varchar(255),
                        password_hash varchar(255), primary key (id))""");
            sql.execute("""
                    create table faculty (created_at timestamp(6), id bigint generated by default as identity,
                        name varchar(255), primary key (id))""");
            sql.execute("""
                    create table department (created_at timestamp(6), faculty_id bigint,
                        id bigint generated by default as identity, code varchar(255), name varchar(255),
                        primary key (id))""");
            sql.execute("alter table if exists department add constraint UKdepartment_code unique (code)");
            sql.execute("""
                    create table course (created_at timestamp(6), department_id bigint,
                        id bigint generated by default as identity, code varchar(255), description varchar(255),
                        name varchar(255), primary key (id))""");
            sql.execute("alter table if exists course add constraint UKcourse_dep_code unique (department_id, code)");
            sql.execute("""
                    create table course_alias (course_id bigint, created_at timestamp(6),
                        id bigint generated by default as identity, alias varchar(255), primary key (id))""");
            sql.execute("""
                    create table lecturer (created_at timestamp(6), department_id bigint,
                        id bigint generated by default as identity, email varchar(255), first_name varchar(255),
                        last_name varchar(255), password_hash varchar(255),
                        title varchar(255) check (title in ('PROFESSOR','ASSOCIATE_PROFESSOR','ASSISTANT_PROFESSOR',
                            'LECTURER','RESEARCH_ASSISTANT','INSTRUCTOR')), primary key (id))""");
            sql.execute("alter table if exists lecturer add constraint UKlecturer_email unique (email)");
            sql.execute("""
                    create table student (created_at timestamp(6), department_id bigint,
                        id bigint generated by default as identity, email varchar(255), first_name varchar(255),
                        last_name varchar(255), password_hash varchar(255), student_number varchar(255),
                        primary key (id))""");
            sql.execute("""
                    create table course_lecturer (course_id bigint, created_at timestamp(6),
                        id bigint generated by default as identity, lecturer_id bigint, primary key (id))""");
            sql.execute("""
                    create table enrollment (course_id bigint, created_at timestamp(6),
                        id bigint generated by default as identity, student_id bigint, primary key (id))""");
            sql.execute("""
                    create table file_record (download_count integer, is_active boolean, year integer,
                        course_id bigint, created_at timestamp(6), id bigint generated by default as identity,
                        size_bytes bigint, uploaded_by_id bigint, description varchar(255), mime_type varchar(255),
                        original_name varchar(255),
                        season varchar(255) check (season in ('FALL','SPRING','SUMMER')),
                        type varchar(255) check (type in ('MIDTERM','FINAL','QUIZ','HOMEWORK','NOTE','SYLLABUS',
                            'LAB','PROJECT','OTHER')),
                        uuid varchar(255), primary key (id))""");
            sql.execute("alter table if exists course add constraint FKcourse_dep foreign key (department_id) references department");
            sql.execute("alter table if exists file_record add constraint FKfile_course foreign key (course_id) references course");
            sql.execute("CREATE EXTENSION IF NOT EXISTS vector");
            sql.execute("ALTER TABLE file_record ADD COLUMN IF NOT EXISTS embedding vector(1024)");

            sql.execute("insert into admin (email, first_name, last_name, password_hash, created_at) values "
                    + "('admin@archmaxim.edu', 'System', 'Admin', '" + adminHash + "', now())");
            sql.execute("insert into faculty (name, created_at) values ('Mühendislik', now())");
            sql.execute("insert into department (code, name, faculty_id, created_at) values ('CENG', 'Bilgisayar', 1, now())");
            sql.execute("insert into course (code, name, department_id, created_at) values "
                    + "('BIL201', 'Bilgisayar Programlama II', 1, now())");
            sql.execute("insert into course_alias (alias, course_id, created_at) values "
                    + "('BP2', 1, now()), ('bp2', 1, now()), ('Bil-Prog II', 1, now()), ('---', 1, now())");
            sql.execute("insert into lecturer (title, first_name, last_name, email, password_hash, department_id, created_at) "
                    + "values ('PROFESSOR', 'Ali', 'Veli', 'ali@uni.edu', 'x', 1, now())");
            sql.execute("insert into file_record (uuid, original_name, type, course_id, uploaded_by_id, year, season, "
                    + "size_bytes, mime_type, created_at) values ('legacy-uuid', 'eski_vize.pdf', 'MIDTERM', 1, 1, 2024, "
                    + "'FALL', 8, 'application/pdf', now())");
        }
    }
}
