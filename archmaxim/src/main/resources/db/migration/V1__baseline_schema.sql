-- The schema as Hibernate generated it before Flyway was introduced. Every
-- statement is idempotent so this also runs cleanly on those older databases.

CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS faculty (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(255),
    created_at timestamp(6)
);

CREATE TABLE IF NOT EXISTS department (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       varchar(255) UNIQUE,
    name       varchar(255),
    faculty_id bigint REFERENCES faculty (id),
    created_at timestamp(6)
);

CREATE TABLE IF NOT EXISTS course (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          varchar(255),
    name          varchar(255),
    description   varchar(255),
    department_id bigint REFERENCES department (id),
    created_at    timestamp(6),
    UNIQUE (department_id, code)
);

CREATE TABLE IF NOT EXISTS course_alias (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alias      varchar(255),
    course_id  bigint REFERENCES course (id),
    created_at timestamp(6)
);

CREATE TABLE IF NOT EXISTS admin (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         varchar(255) UNIQUE,
    password_hash varchar(255),
    first_name    varchar(255),
    last_name     varchar(255),
    created_at    timestamp(6)
);

CREATE TABLE IF NOT EXISTS lecturer (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         varchar(255) CHECK (title IN ('PROFESSOR', 'ASSOCIATE_PROFESSOR', 'ASSISTANT_PROFESSOR',
                                                'LECTURER', 'RESEARCH_ASSISTANT', 'INSTRUCTOR')),
    first_name    varchar(255),
    last_name     varchar(255),
    email         varchar(255) UNIQUE,
    password_hash varchar(255),
    department_id bigint REFERENCES department (id),
    created_at    timestamp(6)
);

CREATE TABLE IF NOT EXISTS student (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_number varchar(255) UNIQUE,
    first_name     varchar(255),
    last_name      varchar(255),
    email          varchar(255) UNIQUE,
    password_hash  varchar(255),
    department_id  bigint REFERENCES department (id),
    created_at     timestamp(6)
);

CREATE TABLE IF NOT EXISTS course_lecturer (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id   bigint REFERENCES course (id),
    lecturer_id bigint REFERENCES lecturer (id),
    created_at  timestamp(6),
    UNIQUE (course_id, lecturer_id)
);

CREATE TABLE IF NOT EXISTS enrollment (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint REFERENCES student (id),
    course_id  bigint REFERENCES course (id),
    created_at timestamp(6),
    UNIQUE (student_id, course_id)
);

CREATE TABLE IF NOT EXISTS file_record (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid           varchar(255) UNIQUE,
    original_name  varchar(255),
    type           varchar(255) CHECK (type IN ('MIDTERM', 'FINAL', 'QUIZ', 'HOMEWORK', 'NOTE',
                                                'SYLLABUS', 'LAB', 'PROJECT', 'OTHER')),
    course_id      bigint REFERENCES course (id),
    uploaded_by_id bigint REFERENCES lecturer (id),
    year           integer,
    season         varchar(255) CHECK (season IN ('FALL', 'SPRING', 'SUMMER')),
    size_bytes     bigint,
    mime_type      varchar(255),
    description    varchar(255),
    download_count integer,
    is_active      boolean,
    created_at     timestamp(6)
);
